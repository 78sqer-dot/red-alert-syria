export function fmtDur(min, lang) {
  if (min < 60) return lang === 'ar' ? `${min} دقيقة` : `${min} min`;
  const h = Math.round((min / 60) * 10) / 10;
  if (lang === 'ar') {
    if (h === 1) return 'ساعة';
    if (h === 1.5) return 'ساعة ونصف';
    if (h === 2) return 'ساعتان';
    if (h === 2.5) return 'ساعتان ونصف';
    return h >= 3 && h <= 10 && Number.isInteger(h) ? `${h} ساعات` : `${h} ساعة`;
  }
  return `${h} h`;
}

